# One-time fetch of self-hosted fonts (Geologica + Wix Madefor Text), cyrillic and latin subsets only.
# Writes woff2 files and fonts.css (local url()s, original unicode-range kept) into Client/wwwroot/fonts.
$ErrorActionPreference = 'Stop'
$out = Join-Path $PSScriptRoot '..\src\NaturalStoneImpex.Client\wwwroot\fonts'
New-Item -ItemType Directory -Force $out | Out-Null

$ua = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36'
$url = 'https://fonts.googleapis.com/css2?family=Geologica:wght@300..500&family=Wix+Madefor+Text:wght@400..600&display=swap'
$css = (Invoke-WebRequest -Uri $url -UserAgent $ua -UseBasicParsing).Content

$blocks = [regex]::Matches($css, '/\*\s*([\w-]+)\s*\*/\s*(@font-face\s*\{[^}]*\})')
$result = New-Object System.Text.StringBuilder
[void]$result.AppendLine('/* Generated by scripts/download-fonts.ps1. Do not edit by hand. Licence: OFL.txt */')
$downloaded = @{}
$matched = 0
foreach ($m in $blocks) {
    $subset = $m.Groups[1].Value
    if ($subset -ne 'cyrillic' -and $subset -ne 'latin') { continue }
    $block = $m.Groups[2].Value
    $matched++
    $family = ([regex]::Match($block, "font-family:\s*'([^']+)'")).Groups[1].Value
    $srcUrl = ([regex]::Match($block, 'url\((https://[^)]+\.woff2)\)')).Groups[1].Value
    if ([string]::IsNullOrEmpty($srcUrl)) { throw "No woff2 src URL found in the $subset block for $family. Google CSS format may have changed." }
    $name = ($family.ToLower() -replace '\s+', '-') + '-' + $subset + '.woff2'
    if (-not $downloaded.ContainsKey($name)) {
        Invoke-WebRequest -Uri $srcUrl -OutFile (Join-Path $out $name) -UseBasicParsing
        $downloaded[$name] = $true
    }
    $local = $block -replace [regex]::Escape($srcUrl), $name
    [void]$result.AppendLine("/* $subset */")
    [void]$result.AppendLine($local)
}
if ($matched -eq 0) { throw "No cyrillic or latin @font-face blocks matched in the Google Fonts CSS. The response format may have changed." }
[System.IO.File]::WriteAllText((Join-Path $out 'fonts.css'), $result.ToString(), (New-Object System.Text.UTF8Encoding($false)))
Write-Host "Done: $($downloaded.Count) font files."
